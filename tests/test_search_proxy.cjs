 assert.match(seen.opts.headers['User-Agent'],/Driv/);
 mode='cached';r=await handler(req());assert.equal(r.status,200);assert.equal(fetches,1);
 mode='limited';r=await handler(req());assert.equal(r.status,429);assert.equal(r.headers.get('retry-after'),'6');assert.equal(fetches,1);
 const before=reserves;
 assert.equal((await handler(req({q:'x'}))).status,400);
 assert.equal((await handler(req({q:'a'.repeat(121)}))).status,400);
 assert.equal((await handler(req({q:'ﬃ'.repeat(41)}))).status,400);
 assert.equal((await handler(req({}, {apikey:'wrong'}))).status,401);
 assert.equal((await handler(req({}, {origin:'https://evil.test'}))).status,403);
 assert.equal((await handler(req({q:'https://private.test/'}))).status,400);
 assert.equal(reserves,before);
 r=await handler(new Request('https://example.test',{method:'OPTIONS',headers:{origin:'https://driv.driveify.se'}}));assert.equal(r.status,204);
